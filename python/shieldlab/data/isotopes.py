# ── Helpers ───────────────────────────────────────────────────────────────────

def get_by_symbol(symbol: str) -> dict | None:
    """Case-insensitive lookup by nuclide symbol."""
    sl = symbol.strip().lower()
    for iso in ISOTOPES:
        if iso["symbol"].lower() == sl:
            return iso
    return None


def half_life_str(half_life_s: float) -> str:
    """Human-readable half-life string."""
    if half_life_s >= 0.5 * _YEAR_S:
        return f"{half_life_s/_YEAR_S:.3g} y"
    if half_life_s >= 0.5 * _DAY_S:
        return f"{half_life_s/_DAY_S:.3g} d"
    if half_life_s >= 0.5 * _HOUR_S:
        return f"{half_life_s/_HOUR_S:.3g} h"
    if half_life_s >= 0.5 * _MIN_S:
        return f"{half_life_s/_MIN_S:.3g} min"
    return f"{half_life_s:.3g} s"


def principal_gammas(iso: dict, min_intensity: float = 0.05) -> list[tuple[float, float]]:
    """Return gamma lines with intensity >= min_intensity."""
    return [(e, i) for e, i in iso.get("gammas", []) if i >= min_intensity]


def list_symbols(category: str | None = None) -> list[str]:
    """Sorted list of nuclide symbols, optionally filtered by category."""
    isos = ISOTOPES if category is None else [x for x in ISOTOPES if x["category"] == category]
    return sorted(x["symbol"] for x in isos)
