def get_by_name(name: str) -> dict | None:
    """Look up a material by exact name (case-insensitive)."""
    nl = name.lower()
    for m in COMPENDIUM:
        if m["name"].lower() == nl:
            return m
    return None


def search(query: str, category: str | None = None) -> list[dict]:
    """Fuzzy name search, optionally filtered by category."""
    ql = query.lower()
    results = [
        m for m in COMPENDIUM
        if ql in m["name"].lower() or (m["formula"] and ql in m["formula"].lower())
    ]
    if category:
        results = [m for m in results if m["category"] == category]
    return results


def list_names(category: str | None = None) -> list[str]:
    """Return sorted list of material names, optionally filtered by category."""
    mats = COMPENDIUM if category is None else [m for m in COMPENDIUM if m["category"] == category]
    return sorted(m["name"] for m in mats)
